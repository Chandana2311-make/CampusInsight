"""
Faculty Dashboard: Academic Support & Mentoring Page
Identifies students needing supportive academic intervention, reviews student-initiated improvement plans,
and records faculty mentoring feedback.
"""
import json
import streamlit as st
import pandas as pd
from ui.components import render_page_header, render_status_badge
from repositories.faculty_repository import FacultyRepository
from repositories.result_repository import ResultRepository
from repositories.improvement_repository import ImprovementRepository
from services.analytics_service import AnalyticsService


def render_faculty_support(user: dict) -> None:
    """Renders the academic support and student intervention interface."""
    render_page_header(
        title="Academic Support & Mentorship 🤝",
        subtitle=f"Student Intervention and Improvement Plan Review | {user.get('full_name')}"
    )

    faculty_repo = FacultyRepository()
    result_repo = ResultRepository()
    analytics_service = AnalyticsService()
    improvement_repo = ImprovementRepository()

    assignments = faculty_repo.get_assigned_subjects(user["id"])
    if not assignments:
        st.warning("No courses assigned to your account.")
        return

    tab1, tab2 = st.tabs(["⚠️ At-Risk / Intervention Candidates", "🎯 Review Student Improvement Plans"])

    # -------------------------------------------------------------
    # TAB 1: At-Risk Students Flagged by Analytics
    # -------------------------------------------------------------
    with tab1:
        st.markdown("### 🔍 Students Flagged for Academic Support")
        st.caption("Identified using supportive criteria: failed subjects, CIE < 45%, or high internal-external disparity.")

        unique_subjects = {f"{a['code']} - {a['name']}": a["subject_id"] for a in assignments}
        selected_sub_label = st.selectbox("Filter by Course:", ["All Assigned Courses"] + list(unique_subjects.keys()))

        if selected_sub_label == "All Assigned Courses":
            all_results = []
            for sub_id in unique_subjects.values():
                all_results.extend(result_repo.get_subject_results(sub_id))
        else:
            all_results = result_repo.get_subject_results(unique_subjects[selected_sub_label])

        at_risk = analytics_service.get_at_risk_students(all_results)

        if not at_risk:
            st.success("🎉 No students currently flagged for critical academic intervention in this course selection.")
        else:
            risk_table = []
            for s in at_risk:
                risk_table.append({
                    "USN": s["usn"],
                    "Student Name": s["student_name"],
                    "Section": s["section"],
                    "Internal (40)": s["internal_marks"],
                    "External (60)": s["external_marks"],
                    "Total (100)": s["total_marks"],
                    "Grade": s["grade"],
                    "Intervention Priority": s["risk_level"],
                    "Diagnostic Reason": s["primary_issue"]
                })
            st.dataframe(pd.DataFrame(risk_table), use_container_width=True, hide_index=True)

    # -------------------------------------------------------------
    # TAB 2: Review Student Improvement Plans
    # -------------------------------------------------------------
    with tab2:
        st.markdown("### 📋 Student Academic Roadmaps")
        st.caption("Review plans generated by students, inspect weekly commitments, and provide formal mentoring feedback.")

        plans = improvement_repo.list_all_plans_for_review()
        if not plans:
            st.info("No active student improvement plans found.")
        else:
            for p in plans:
                status_badge = render_status_badge(p["status"])
                recs = json.loads(p["recommendations_json"]) if p.get("recommendations_json") else []

                with st.expander(f"Plan #{p['id']}: {p['student_name']} ({p['usn']}) – {p['title']} [{p['status']}]"):
                    st.markdown(f"""
                        <div style="font-size: 0.9rem; margin-bottom: 0.75rem;">
                            <b>Target SGPA:</b> {p['target_sgpa'] or 8.5} | 
                            <b>Status:</b> {status_badge} | 
                            <b>Last Updated:</b> {p['updated_at']}
                        </div>
                    """, unsafe_allow_html=True)

                    if recs:
                        st.markdown("##### 📌 Generated Action Recommendations:")
                        for r in recs:
                            st.markdown(f"- **{r.get('subject_code')}:** {r.get('suggested_action')}")

                    # Mentoring Feedback Form
                    st.markdown("---")
                    st.markdown("##### 💬 Faculty Mentoring Review:")
                    if p.get("faculty_feedback"):
                        st.info(f"**Current Feedback:** {p['faculty_feedback']} *(Reviewed by {p.get('reviewer_name') or 'Faculty'})*")

                    with st.form(f"feedback_form_{p['id']}"):
                        feedback_text = st.text_area(
                            "Enter Mentoring Guidance / Approval Notes:",
                            value=p.get("faculty_feedback") or "",
                            placeholder="e.g. Plan reviewed and approved. Focus on Chapter 4 numericals and meet me during Tuesday office hours."
                        )
                        c_rev, c_comp = st.columns(2)
                        with c_rev:
                            submit_review = st.form_submit_button("Save Feedback & Mark 'Faculty Reviewed'", type="primary")
                        with c_comp:
                            submit_complete = st.form_submit_button("Mark Plan as 'Completed'")

                        if submit_review:
                            if not feedback_text:
                                st.error("Please provide feedback comments.")
                            else:
                                improvement_repo.add_faculty_feedback(
                                    plan_id=p["id"],
                                    faculty_user_id=user["id"],
                                    feedback=feedback_text,
                                    status="Faculty Reviewed"
                                )
                                st.success("Mentoring feedback saved!")
                                st.rerun()

                        if submit_complete:
                            improvement_repo.update_status(plan_id=p["id"], status="Completed")
                            st.success("Plan marked as completed.")
                            st.rerun()
